"""给模型看的文本的收尾处理：超长时**取头尾两段**。

它本来在 shell.py 和 grep.py 里各有一份（逐字符相同，连那句"取头尾不是只留开头"的
理由也一样），fetch_web 是**第三处**要用它的地方。两份还能容忍，三份就是"同一份事实
写三遍" —— 而这份事实决定的恰好是"模型还能不能看到最后那句话"，正是最不该各写一份的
那种东西（doc/guide.md 里那版 truncate 只留开头，正是要防的错法）。

**第四处（web_search）当时漏了，是 review 时补上的** —— 它自己那份"只留开头"没跟着换
过来，而那里的尾巴是最后几条搜索结果。所以规矩要写成"新工具一律调这里"，而不是"凑够
三份才抽"：漏掉的那一处不会报错，只会静默少给模型几条结果。

**`_truncate` 这个名字和各自的默认上限仍然留在 shell.py / grep.py 里。** 上限是每个工具
自己的常量（8000 / 16000 / 12000），而那几个名字是各自模块的测试面（test_shell.py /
test_grep.py 直接 import 它们）。所以这里是"实现搬走、门面留下"，不是把三个工具的常量
也合成一个 —— 合成之后，改 shell 的输出上限就得去动三个工具的公共常量。
"""


def truncate(text: str, limit: int) -> str:
    """文本不超过 limit 就原样返回，否则取头尾两段并在中间写明省略了多少字符。

    **刻意不是"只留开头"** —— 命令输出和网页正文的关键信息通常压在最后：报错、
    traceback、测试失败的汇总行、结论段。只留开头会让模型看到一整屏正常内容，而真正的
    那半句正好被切掉 —— 那比截断本身更危险。
    """
    if len(text) <= limit:
        return text

    head = limit * 2 // 3
    tail = limit - head
    return f"{text[:head]}\n…[中间省略 {len(text) - limit} 字符]…\n{text[-tail:]}"
